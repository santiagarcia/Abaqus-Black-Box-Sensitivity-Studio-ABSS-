bool isForeignMaterialLibrary(const fs::path& p) {
    std::error_code ec;
    if (!fs::is_regular_file(p, ec)) return false;
    const std::string ext = lowerStr(p.extension().string());
    if (isElf(p)) return true;
    return (ext == ".dll" || ext == ".so") && lowerStr(p.filename().string()) != "standardu.dll";
}

std::vector<std::string> elfExportNames(const fs::path& so) {
    const std::string b = readAll(so);
    auto u16 = [&](size_t o) { std::uint16_t v; std::memcpy(&v, b.data() + o, 2); return v; };
    auto u32 = [&](size_t o) { std::uint32_t v; std::memcpy(&v, b.data() + o, 4); return v; };
    auto u64 = [&](size_t o) { std::uint64_t v; std::memcpy(&v, b.data() + o, 8); return v; };
    if (b.size() < 64 || b.compare(0, 4, "\x7f" "ELF") != 0 || b[4] != 2 || b[5] != 1)
        throw std::runtime_error(so.string() + " is not a 64-bit little-endian ELF shared object");
    const std::uint64_t shoff = u64(0x28);
    const std::uint16_t shentsize = u16(0x3A), shnum = u16(0x3C);
    if (shoff + static_cast<std::uint64_t>(shnum) * shentsize > b.size()) throw std::runtime_error("truncated ELF file " + so.string());
    std::vector<std::string> names;
    for (std::uint16_t i = 0; i < shnum; ++i) {
        const size_t sh = shoff + static_cast<size_t>(i) * shentsize;
        if (u32(sh + 4) != 11) continue;  // SHT_DYNSYM
        const std::uint64_t off = u64(sh + 0x18), size = u64(sh + 0x20), entsize = u64(sh + 0x38);
        const std::uint32_t link = u32(sh + 0x28);
        const size_t strsh = shoff + static_cast<size_t>(link) * shentsize;
        const std::uint64_t stroff = u64(strsh + 0x18), strsize = u64(strsh + 0x20);
        if (!entsize || off + size > b.size() || stroff + strsize > b.size()) throw std::runtime_error("corrupt ELF symbol table in " + so.string());
        for (std::uint64_t s = off; s + entsize <= off + size; s += entsize) {
            const std::uint32_t name = u32(s);
            const unsigned char info = static_cast<unsigned char>(b[s + 4]);
            const std::uint16_t shndx = u16(s + 6);
            if ((info & 0xf) != 2 || shndx == 0 || (info >> 4) == 0) continue;  // defined global/weak FUNC
            if (name < strsize) names.emplace_back(b.c_str() + stroff + name);
        }
    }
    std::sort(names.begin(), names.end());
    names.erase(std::unique(names.begin(), names.end()), names.end());
    return names;
}

UserSubroutineLibrary prepareMaterialBridge(const fs::path& abaqusHome, const fs::path& libIn, const fs::path& dir,
                                            const std::function<void(const fs::path&)>& buildC,
                                            const std::function<std::vector<std::string>(const fs::path&)>& peExports,
                                            const LogFn& log) {
    const bool elf = isElf(libIn);
    const auto names = elf ? elfExportNames(libIn) : peExports(libIn);
    const Abi abi = detectAbi(names, libIn);
    UserSubroutineLibrary out;
    out.kind = std::string("foreign material library (") + (elf ? "Linux shared object, run under WSL" : "Windows DLL") + ")";
    headerRequirements(libIn, out, log);
    out.requiresSdvini = abi.kind == "regular" && !abi.init.empty();
    if (log)
        log("Material bridge: " + libIn.filename().string() + " exports " +
            (abi.kind == "umat" ? "a standard UMAT '" + abi.step + "'" : "a deformation-gradient update '" + abi.step + "'") +
            (abi.init.empty() ? std::string() : " and the state initialiser '" + abi.init + "'") + ".");

    fs::create_directories(dir);
    const fs::path lib = dir / libIn.filename();
    if (fs::absolute(libIn) != fs::absolute(lib)) fs::copy_file(libIn, lib, fs::copy_options::overwrite_existing);
    writeText(dir / "abss_matbridge.py", kHelperSource);

    // Helper command line. A Linux .so runs in ABSS's native ELF host (abss_elfhost.exe, installed next to ABSS) when
    // that host can load it; otherwise under WSL.
    std::vector<std::string> abiArgs = {"--abi", abi.kind};
    if (abi.kind == "regular") {
        abiArgs.insert(abiArgs.end(), {"--step", abi.step});
        if (!abi.init.empty()) abiArgs.insert(abiArgs.end(), {"--init", abi.init});
    } else {
        abiArgs.insert(abiArgs.end(), {"--umat", abi.step});
        if (!abi.init.empty()) abiArgs.insert(abiArgs.end(), {"--sdvini", abi.init});
    }
    if (out.requiredNtens) abiArgs.insert(abiArgs.end(), {"--ntens", std::to_string(out.requiredNtens)});
    if (out.requiredNstatv) abiArgs.insert(abiArgs.end(), {"--nstatv", std::to_string(out.requiredNstatv)});
    if (out.requiredNprops) abiArgs.insert(abiArgs.end(), {"--nprops", std::to_string(out.requiredNprops)});
    std::vector<std::string> cmd;
    std::string hostKind = elf ? "WSL" : "Windows helper";
    if (elf) {
        const fs::path host = selfDirectory() / "abss_elfhost.exe";
        std::error_code ec;
        if (fs::exists(host, ec)) {
            std::vector<std::string> args = {"--lib", lib.string()};
            args.insert(args.end(), abiArgs.begin(), abiArgs.end());
            args.push_back("--selftest");
            const auto st = runProcess(host.string(), args, dir.string(), 120, nullptr);
            if (st.exitCode == 0 && st.output.find("ABSS-SELFTEST OK") != std::string::npos) {
                cmd = {host.string(), "--lib", lib.string()};
                hostKind = "native ELF host";
                if (log) log("Material bridge: " + libIn.filename().string() + " runs natively in ABSS's ELF host (no WSL needed).");
            } else if (log) {
                log("Material bridge: the native ELF host cannot run " + libIn.filename().string() + " (" +
                    st.output.substr(st.output.size() > 400 ? st.output.size() - 400 : 0) + "); trying WSL.");
            }
        }
    }
    if (elf && cmd.empty()) {
        const auto wsl = which("wsl.exe");
        const std::string how =
            " To run Linux material libraries, install the Windows Subsystem for Linux once (administrator PowerShell: "
            "`wsl --install -d Ubuntu`, then restart Windows) and the runtime libraries the model needs (in Ubuntu: "
            "`sudo apt install python3 liblapack3 libblas3 libgfortran5`). Alternatively ask the model's author for a "
            "Windows build (a .dll or .obj), which needs no WSL.";
        if (!wsl) throw std::runtime_error(libIn.filename().string() + " is a Linux shared object, and WSL is not installed." + how);
        const auto probe = runProcess(*wsl, {"-e", "python3", "-c", "print('ok')"}, dir.string(), 300, nullptr);
        if (probe.exitCode != 0 || probe.output.find("ok") == std::string::npos)
            throw std::runtime_error(libIn.filename().string() + " is a Linux shared object, but WSL has no working Linux "
                                     "distribution with python3." + how);
        cmd = {*wsl, "-e", "python3", wslPath(dir / "abss_matbridge.py"), "--lib", wslPath(lib)};
    } else if (!elf) {
        fs::path py = abaqusHome / "win_b64" / "tools" / "SMApy" / "python3.10" / "python.exe";
        std::error_code ec;
        if (!fs::exists(py, ec)) {
            const auto any = which("python.exe");
            if (!any) throw std::runtime_error("No Python was found to host the material helper (looked for Abaqus's bundled Python at " + py.string() + ").");
            py = *any;
        }
        cmd = {py.string(), (dir / "abss_matbridge.py").string(), "--lib", lib.string()};
    }
    cmd.insert(cmd.end(), abiArgs.begin(), abiArgs.end());
    std::string line;
    for (const auto& a : cmd) line += (line.empty() ? "" : " ") + quoteArg(a);
    writeText(dir / "abss_bridge.cmd", line + "\r\n");

    // Self-test: the helper loads the library and resolves the entry points (catches missing runtime libraries).
    std::vector<std::string> args(cmd.begin() + 1, cmd.end());
    args.push_back("--selftest");
    const auto st = runProcess(cmd.front(), args, dir.string(), 300, nullptr);
    if (st.exitCode != 0 || st.output.find("ABSS-SELFTEST OK") == std::string::npos) {
        std::string why = st.output.substr(st.output.size() > 1500 ? st.output.size() - 1500 : 0);
        std::string hint;
        if (why.find("cannot open shared object") != std::string::npos)
            hint = " A runtime library the model needs is missing in Linux; for the usual Fortran/LAPACK dependencies run "
                   "in Ubuntu: `sudo apt install liblapack3 libblas3 libgfortran5`.";
        throw std::runtime_error("The material library could not be loaded by the helper: " + why + hint);
    }
    if (log) log("Material helper self-test passed (" + hostKind + ").");

    // The bridge UMAT/SDVINI, built like any C user subroutine.
    const fs::path srcDir = dir / "bridge_src";
    fs::create_directories(srcDir);
    writeText(srcDir / "abss_matbridge_umat.c", kShimSource);
    buildC(srcDir / "abss_matbridge_umat.c");
    out.libraryDir = dir.string();
    out.builtHere = true;
    out.message = "Built the material bridge for " + libIn.filename().string() + " in " + dir.string() +
                  " (Abaqus calls UMAT/SDVINI in standardU.dll, which run the library through the " + hostKind + ").";
    if (log) log(out.message);
    return out;
}

UserSubroutineLibrary prepareMaterialBridgePosix(const std::string& abaqusCommand, const fs::path& libIn, const fs::path& dir,
                                                 const LogFn& log) {
    if (!isElf(libIn)) throw std::runtime_error(libIn.filename().string() + " is not a Linux shared object");
    const Abi abi = detectAbi(elfExportNames(libIn), libIn);
    UserSubroutineLibrary out;
    out.kind = "foreign material library (Linux shared object, loaded in-process)";
    headerRequirements(libIn, out, log);
    out.requiresSdvini = abi.kind == "regular" && !abi.init.empty();
    fs::create_directories(dir);
    const fs::path lib = fs::absolute(dir / libIn.filename());
    if (fs::absolute(libIn) != lib) fs::copy_file(libIn, lib, fs::copy_options::overwrite_existing);
    std::ostringstream c;
    c << "/* Generated by ABSS: UMAT/SDVINI wrapper that runs " << libIn.filename().string() << " in-process. */\n"
      << "#include <dlfcn.h>\n#include <math.h>\n#include <pthread.h>\n#include <stddef.h>\n#include <stdio.h>\n#include <stdlib.h>\n"
      << "#define LIB \"" << lib.string() << "\"\n"
      << "#define STEP \"" << abi.step << "\"\n#define INIT \"" << abi.init << "\"\n"
      << "#define REGULAR " << (abi.kind == "regular" ? 1 : 0) << "\n"
      << "#define NEED_NTENS " << out.requiredNtens << "\n#define NEED_NSTATV " << out.requiredNstatv << "\n"
      << "#define NEED_NPROPS " << out.requiredNprops << "\n"
      << R"__(
static pthread_mutex_t lk = PTHREAD_MUTEX_INITIALIZER;
static void *h, *stepF, *initF;
static void die(const char* m, int noel) {
  fprintf(stderr, "\n***ERROR: ABSS material bridge (element %d): %s\n", noel, m);
  fflush(stderr);
  exit(86);
}
static void load(void) {
  if (h) return;
  h = dlopen(LIB, RTLD_NOW | RTLD_LOCAL);
  if (!h) die(dlerror(), 0);
  stepF = dlsym(h, STEP);
  if (!stepF) die("entry point " STEP " not found", 0);
  if (INIT[0]) { initF = dlsym(h, INIT); if (!initF) die("state initialiser " INIT " not found", 0); }
}
typedef void (*regular_fn)(int, int, int, int, const double*, double*, double*, double*, const double*, const double*,
                           double, double, double, double, const double*, const double*, const int*, const int*, int, int, double*);
typedef void (*reginit_fn)(int, int, double*, const double*, const int*, const int*);
typedef void (*umat_fn)(double*, double*, double*, double*, double*, double*, double*, double*, double*, double*, double*,
                        double*, double*, double*, double*, double*, double*, double*, char*, int*, int*, int*, int*, double*,
                        int*, double*, double*, double*, double*, double*, double*, int*, int*, int*, int*, int*, int*, size_t);
typedef void (*sdvini_fn)(double*, double*, int*, int*, int*, int*, int*, int*);

void umat_(double* stress, double* statev, double* ddsdde, double* sse, double* spd, double* scd, double* rpl,
           double* ddsddt, double* drplde, double* drpldt, double* stran, double* dstran, double* time, double* dtime,
           double* temp, double* dtemp, double* predef, double* dpred, char* cmname, int* ndi, int* nshr, int* ntens,
           int* nstatv, double* props, int* nprops, double* coords, double* drot, double* pnewdt, double* celent,
           double* dfgrd0, double* dfgrd1, int* noel, int* npt, int* layer, int* kspt, int* jstep, int* kinc, size_t len) {
  pthread_mutex_lock(&lk);
  load();
  if (NEED_NTENS && *ntens != NEED_NTENS) die("NTENS does not match the library's requirement", *noel);
  if (NEED_NSTATV && *nstatv != NEED_NSTATV) die("NSTATV does not match the library's requirement", *noel);
  if (NEED_NPROPS && *nprops != NEED_NPROPS) die("NPROPS does not match the library's requirement", *noel);
#if REGULAR
  {
    double pn = 1.0;
    ((regular_fn)stepF)(1, *nprops, *ntens, *nstatv, props, stress, statev, ddsdde, dfgrd0, dfgrd1, *dtime, time[0], *temp,
                        *dtemp, coords, celent, noel, npt, jstep[0], *kinc, &pn);
    if (pn < *pnewdt) *pnewdt = pn;
  }
#else
  ((umat_fn)stepF)(stress, statev, ddsdde, sse, spd, scd, rpl, ddsddt, drplde, drpldt, stran, dstran, time, dtime, temp, dtemp,
                   predef, dpred, cmname, ndi, nshr, ntens, nstatv, props, nprops, coords, drot, pnewdt, celent, dfgrd0, dfgrd1,
                   noel, npt, layer, kspt, jstep, kinc, len);
#endif
  for (int k = 0; k < *ntens; ++k)
    if (!isfinite(stress[k])) die("the material returned a non-finite stress", *noel);
  pthread_mutex_unlock(&lk);
}

void sdvini_(double* statev, double* coords, int* nstatv, int* ncrds, int* noel, int* npt, int* layer, int* kspt) {
  pthread_mutex_lock(&lk);
  load();
  if (!initF) die("Abaqus called SDVINI but the material library has no state initialiser", *noel);
#if REGULAR
  ((reginit_fn)initF)(1, *nstatv, statev, coords, noel, npt);
#else
  ((sdvini_fn)initF)(statev, coords, nstatv, ncrds, noel, npt, layer, kspt);
#endif
  pthread_mutex_unlock(&lk);
}
)__";
    writeText(dir / "abss_bridge.c", c.str());
    if (log) log("Material bridge (Linux): " + libIn.filename().string() + " is called in-process through a generated UMAT/SDVINI; building it with `abaqus make`...");
    const auto r = runProcess(abaqusCommand, {"make", "library=abss_bridge.c", "directory=" + dir.string()}, dir.string(), 1800, nullptr);
    std::error_code ec;
    if (!fs::exists(dir / "libstandardU.so", ec))
        throw std::runtime_error("`abaqus make` did not build the bridge library:\n" + r.output.substr(r.output.size() > 1500 ? r.output.size() - 1500 : 0));
    out.libraryDir = dir.string();
    out.builtHere = true;
    out.message = "Built the material bridge for " + libIn.filename().string() + " in " + dir.string() + " (in-process).";
    if (log) log(out.message);
    return out;
}

