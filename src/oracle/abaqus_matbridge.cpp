struct Abi {
    std::string kind;  ///< "umat" or "regular"
    std::string step, init;
};

Abi detectAbi(const std::vector<std::string>& names, const fs::path& lib) {
    std::set<std::string> s(names.begin(), names.end());
    Abi a;
    for (const char* n : {"umat_", "umat", "UMAT"})
        if (s.count(n)) {
            a.kind = "umat";
            a.step = n;
            for (const char* m : {"sdvini_", "sdvini", "SDVINI"})
                if (s.count(m)) a.init = m;
            return a;
        }
    std::vector<std::string> inits, others;
    for (const auto& n : names) {
        if (n.empty() || n[0] == '_') continue;  // runtime/compiler internals
        (lowerStr(n).find("sdvini") != std::string::npos ? inits : others).push_back(n);
    }
    if (others.size() == 1 && inits.size() <= 1) {
        a.kind = "regular";
        a.step = others.front();
        if (!inits.empty()) a.init = inits.front();
        return a;
    }
    std::string list;
    for (const auto& n : names) list += (list.empty() ? "" : ", ") + n;
    throw std::runtime_error(lib.filename().string() + " does not export a recognised material entry point. Expected a "
                             "standard UMAT (umat_/umat, optional sdvini) or one update routine plus an optional "
                             "*sdvini initialiser. Exported functions: " + (list.empty() ? std::string("(none)") : list));
}

/// `#define <PREFIX>_NTENS 6` style requirements from a C header shipped with the library.
void headerRequirements(const fs::path& lib, UserSubroutineLibrary& out, const LogFn& log) {
    static const std::regex def(R"(#\s*define\s+\w*?(NTENS|NSTATV|NPROPS)\s+(\d+))");
    std::set<fs::path> dirs = {lib.parent_path(), lib.parent_path().parent_path()};
    std::error_code ec;
    for (const auto& d : dirs)
        for (const auto& e : fs::directory_iterator(d, ec)) {
            if (lowerStr(e.path().extension().string()) != ".h") continue;
            const std::string t = readAll(e.path());
            for (std::sregex_iterator it(t.begin(), t.end(), def), end; it != end; ++it) {
                const int v = std::stoi((*it)[2]);
                const std::string k = (*it)[1];
                (k == "NTENS" ? out.requiredNtens : k == "NSTATV" ? out.requiredNstatv : out.requiredNprops) = v;
            }
            if (out.requiredNtens || out.requiredNstatv || out.requiredNprops) {
                if (log)
                    log("Material library requirements from " + e.path().filename().string() + ": NTENS=" +
                        std::to_string(out.requiredNtens) + ", NSTATV=" + std::to_string(out.requiredNstatv) +
                        ", NPROPS=" + std::to_string(out.requiredNprops) + " (checked at every call).");
                return;
            }
        }
}

