// Material bridge. Some compiled material models cannot be loaded by Abaqus at all: a Linux shared object on a
// Windows Abaqus, or a library whose entry point is not the Abaqus UMAT signature (for example a deformation-gradient
// driven "regular" update with its own state initialiser). ABSS still treats them as opaque materials:
//
//   Abaqus job --> standardU.dll (generated here): umat / sdvini --pipe--> helper process --> the foreign library
//
// The generated UMAT/SDVINI serialise every argument the library can use, the helper (abss_matbridge.py, run by WSL's
// python3 for a .so or by Abaqus's bundled Python for a .dll) calls the library and sends back STRESS, STATEV, DDSDDE,
// SSE/SPD/SCD/RPL, PNEWDT. One helper per Abaqus process; calls are serialised, so libraries with static storage and
// a one-time initialisation (common for Fortran models) are safe. Whatever the library prints goes to the job's
// abss_bridge.log, never into the protocol. A library that terminates its process (e.g. XIT on inadmissible input)
// stops the Abaqus job with a message pointing to that log.
#include "abaqus_matbridge.hpp"

