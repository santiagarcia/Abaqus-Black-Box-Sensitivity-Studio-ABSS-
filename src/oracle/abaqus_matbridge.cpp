std::string lowerStr(std::string s) {
    for (char& c : s) c = static_cast<char>(std::tolower(static_cast<unsigned char>(c)));
    return s;
}

void writeText(const fs::path& p, const std::string& s) {
    std::ofstream f(p, std::ios::binary);
    if (!f) throw std::runtime_error("Cannot write " + p.string());
    f << s;
}

std::string readAll(const fs::path& p) {
    std::ifstream f(p, std::ios::binary);
    std::ostringstream os;
    os << f.rdbuf();
    return os.str();
}

bool isElf(const fs::path& p) {
    std::ifstream f(p, std::ios::binary);
    char m[4] = {};
    f.read(m, 4);
    return f.gcount() == 4 && m[0] == 0x7f && m[1] == 'E' && m[2] == 'L' && m[3] == 'F';
}

/// Windows command-line quoting for one argument (paths and plain options; no embedded quotes expected).
std::string quoteArg(const std::string& a) {
    if (!a.empty() && a.find_first_of(" \t\"") == std::string::npos) return a;
    return "\"" + a + "\"";
}

/// Folder of the running ABSS executable (abss.exe / abss-cli.exe), where abss_elfhost.exe is installed.
fs::path selfDirectory() {
#ifdef _WIN32
    wchar_t buf[4096];
    const DWORD n = GetModuleFileNameW(nullptr, buf, 4096);
    return fs::path(std::wstring(buf, n)).parent_path();
#else
    return fs::read_symlink("/proc/self/exe").parent_path();
#endif
}

/// C:\dir\file -> /mnt/c/dir/file (WSL's default automount).
std::string wslPath(const fs::path& p) {
    std::string s = fs::absolute(p).string();
    std::replace(s.begin(), s.end(), '\\', '/');
    if (s.size() >= 2 && s[1] == ':') s = "/mnt/" + std::string(1, static_cast<char>(std::tolower(static_cast<unsigned char>(s[0])))) + s.substr(2);
    return s;
}

